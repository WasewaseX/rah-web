"""Reference oracle entry for the DUOLINGO-RE parity gate.

Runs DUOLINGO'S OWN implementation (reference_py3.py - a mechanical py2->py3
shim of upstream experiment.py: iteritems->items, intern->sys.intern,
binary->text gzip handles, plus an order-pin switch for parity) on a fixture
generated by the TypeScript gate, with the training order pinned, and dumps
final weights + test predictions for cross-language diffing.

Usage: python3 parity_entry.py <fixture.json> <out.json>
"""

import json
import random
import sys

from reference_py3 import Instance, SpacedRepetitionModel


def mk(d):
    return Instance(
        p=d["p"],
        t=d["t"],
        fv=[(k, x) for k, x in d["fv"]],
        h=d["h"],
        a=0.0,
        lang="",
        right=0,
        wrong=0,
        ts=0,
        uid="",
        lexeme="",
    )


def main():
    fin, fout = sys.argv[1], sys.argv[2]
    with open(fin) as f:
        data = json.load(f)
    train = [mk(d) for d in data["train"]]
    test = [mk(d) for d in data["test"]]
    # Parity requires an IDENTICAL training sequence on both sides - their
    # train() shuffles with random.shuffle, so pin it to identity here. The
    # math (SGD updates, gradients, clips) is untouched.
    random.shuffle = lambda x: None
    m = SpacedRepetitionModel(method="hlr")
    m.train(train)
    preds = []
    for inst in test:  # test already holds Instance objects
        p, h = m.predict(inst)
        preds.append([p, h])
    with open(fout, "w") as f:
        json.dump({"weights": dict(m.weights), "preds": preds}, f)


main()
